    static void mover(int[] posicionPersonaje, int[][] mundo) {

        final int FILA = 0, COLUMNA = 1;
        Scanner scanner = new Scanner(System.in);
        
        int filaOriginal = posicionPersonaje[FILA];
        int columnaOriginal = posicionPersonaje[COLUMNA];

        System.out.print("WASD > ");
        String opcionDelUsuario = scanner.nextLine();

        if (opcionDelUsuario.equalsIgnoreCase("w")) {
            posicionPersonaje[FILA]--;
        } else if (opcionDelUsuario.equalsIgnoreCase("a")) {
            posicionPersonaje[COLUMNA]--;
        } else if (opcionDelUsuario.equalsIgnoreCase("s")) {
            posicionPersonaje[FILA]++;
        } else if (opcionDelUsuario.equalsIgnoreCase("d")) {
            posicionPersonaje[COLUMNA]++;
        }

        if (mundo[posicionPersonaje[FILA]][posicionPersonaje[COLUMNA]]%2!=0){
            posicionPersonaje[FILA] = filaOriginal;
            posicionPersonaje[COLUMNA] = columnaOriginal;
        }
    }

    static void limpiarPantalla() {
        System.out.print("\033[H\033[2J");
        System.out.flush();
    }

    static void imprimir(int[][] mundo, int[] posicionPersonaje) {

        final int FILA = 0, COLUMNA = 1;
        final String PERSONAJE = "_O_";
        final String[] MOSAICOS = { " . ", "[#]", " · ", "~~~", "'''", ":::", ", '", "/^\\", "^Y^", ":|:" };

        final int VIEWPORT = 10;

        limpiarPantalla();
        for (int fila = posicionPersonaje[FILA] - VIEWPORT; fila < posicionPersonaje[FILA] + VIEWPORT; fila++) {
            for (int columna = posicionPersonaje[COLUMNA] - VIEWPORT; columna < posicionPersonaje[COLUMNA]
                    + VIEWPORT; columna++) {
                if (fila == posicionPersonaje[FILA] && columna == posicionPersonaje[COLUMNA]) {
                    System.out.print(PERSONAJE);
                } else {
                    System.out.print(MOSAICOS[mundo[fila][columna]]);
                }
            }
            System.out.println();
        }
    }
